CREATE TABLE genres (
    id              VARCHAR(100) PRIMARY KEY,
    canonical_name  VARCHAR(100) NOT NULL,
    display_name    VARCHAR(100) NOT NULL,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_genres_canonical_name CHECK (length(btrim(canonical_name)) > 0),
    CONSTRAINT ck_genres_display_name CHECK (length(btrim(display_name)) > 0)
);
CREATE UNIQUE INDEX uq_genres_canonical_name_ci ON genres (lower(canonical_name));

CREATE TABLE genre_aliases (
    id          VARCHAR(100) PRIMARY KEY,
    genre_id    VARCHAR(100) NOT NULL REFERENCES genres(id) ON DELETE RESTRICT,
    alias_value VARCHAR(100) NOT NULL,
    CONSTRAINT ck_genre_aliases_value CHECK (length(btrim(alias_value)) > 0)
);
CREATE UNIQUE INDEX uq_genre_aliases_value_ci ON genre_aliases (lower(alias_value));
CREATE INDEX ix_genre_aliases_genre ON genre_aliases (genre_id);

